#!/usr/bin/env node
/**
 * Baseline layout-quality report for one or more project roots.
 *
 * Usage:
 *   node scripts/layout-baseline.mjs --root . --root fixtures/ts-web
 *
 * Requires a built CLI (npm run build) because it runs the real
 * `vibemap inspect <map> --json` pipeline, which is what the viewer and
 * `vibemap check` see.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const argv = process.argv.slice(2);
const roots = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--root' && argv[i + 1]) {
    roots.push(path.resolve(argv[++i]));
  }
}
if (!roots.length) roots.push(process.cwd());

const cli = path.join(process.cwd(), 'dist', 'cli.js');
if (!fs.existsSync(cli)) {
  console.error(`Missing ${cli}. Run: npm run build`);
  process.exit(1);
}

function collectMaps(dir) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const abs = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...collectMaps(abs));
    else if (entry.isFile() && entry.name.endsWith('.vmap.yaml')) out.push(abs);
  }
  return out.sort();
}

function mapId(root, file) {
  const base = path.join(root, '.vibemap', 'maps');
  return path.relative(base, file).split(path.sep).join('/').replace(/\.vmap\.yaml$/, '');
}

function inspect(root, id) {
  const out = execFileSync(process.execPath, [cli, '--root', root, 'inspect', id, '--json'], {
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return JSON.parse(out);
}

const columns = [
  'map',
  'type',
  'nodes',
  'edges',
  'groups',
  'nodeOverlaps',
  'groupOverlaps',
  'groupMarginViolations',
  'groupContainmentViolations',
  'edgeNodeCrossings',
  'edgeCrossings',
  'edgeGroupCrossings',
  'groupLabelOverlaps',
  'labelOverlaps',
  'portViolations',
  'maxNodeDegree',
  'aspect',
  'bends',
  'pinned',
  'canvas',
];

const lines = [];
lines.push('# Layout quality baseline');
lines.push('');
lines.push('Generated by `node scripts/layout-baseline.mjs --root . --root fixtures/ts-web`.');
lines.push('Layout engine: **legacy** (`src/core/layout.ts`).');
lines.push('');

let total = 0;
for (const root of roots) {
  const files = collectMaps(path.join(root, '.vibemap', 'maps'));
  lines.push(`## ${root}`);
  lines.push('');
  if (!files.length) {
    lines.push('No `.vibemap/maps/**/*.vmap.yaml` found under this root.');
    lines.push('');
    continue;
  }
  lines.push(`| ${columns.join(' | ')} |`);
  lines.push(`| ${columns.map(() => '---').join(' | ')} |`);
  for (const file of files) {
    const id = mapId(root, file);
    total++;
    try {
      const report = inspect(root, id);
      const q = report.quality;
      const row = [
        id,
        report.type,
        report.nodes,
        report.edges,
        report.groups,
        q.nodeOverlaps,
        q.groupOverlaps,
        q.groupMarginViolations,
        q.groupContainmentViolations,
        q.edgeNodeCrossings,
        q.edgeCrossings,
        q.edgeGroupCrossings,
        q.groupLabelOverlaps,
        q.labelOverlaps,
        q.portViolations,
        q.maxNodeDegree,
        q.aspectRatio.toFixed(2),
        q.bends,
        report.pinned,
        `${Math.round(report.width)}x${Math.round(report.height)}`,
      ];
      lines.push(`| ${row.join(' | ')} |`);
    } catch (error) {
      const message = String(error && error.message ? error.message : error).replace(/\|/g, '\\|').replace(/\n/g, ' ');
      lines.push(`| ${id} | ERROR | ${message} |`);
    }
  }
  lines.push('');
}

lines.push(`Maps measured: ${total}`);
lines.push('');

const outFile = path.join(process.cwd(), 'docs', 'layout-baseline.md');
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, `${lines.join('\n')}\n`, 'utf8');
process.stdout.write(`${lines.join('\n')}\n`);
console.error(`Wrote ${outFile}`);
