import fs from 'node:fs';
import path from 'node:path';
import { listMapIds, loadProject, readLayout } from '../src/core/project.js';
import { loadMap } from '../src/core/maps.js';
import { layoutMap } from '../src/core/layout.js';
import { layoutGraphElk, type ElkNodePlacement } from '../src/core/layout-elk.js';
import { layoutQuality } from '../src/core/layout-quality.js';
import type { GraphMap, LayoutResult, Theme } from '../src/core/types.js';

interface Row {
  root: string;
  map: string;
  engine: string;
  variant: string;
  nodes: number;
  edges: number;
  nodeX: number;
  groupX: number;
  containment: number;
  edgeNodeX: number;
  edgeX: number;
  edgeGroupX: number;
  groupLabelX: number;
  labelX: number;
  maxDeg: number;
  aspect: string;
  ms: string;
  hard: number;
}

function parseRoots(argv: string[]): string[] {
  const roots: string[] = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--root' && argv[i + 1]) roots.push(path.resolve(argv[++i]!));
  }
  return roots.length ? roots : [process.cwd()];
}

function summarize(map: GraphMap, layout: LayoutResult, theme: Theme, root: string, engine: string, variant: string, ms: number): Row {
  const q = layoutQuality(layout, theme);
  const hard = q.nodeOverlaps + q.groupOverlaps + q.groupContainmentViolations + q.edgeNodeCrossings + q.labelOverlaps;
  return {
    root,
    map: '',
    engine,
    variant,
    nodes: map.nodes.length,
    edges: map.edges.length,
    nodeX: q.nodeOverlaps,
    groupX: q.groupOverlaps,
    containment: q.groupContainmentViolations,
    edgeNodeX: q.edgeNodeCrossings,
    edgeX: q.edgeCrossings,
    edgeGroupX: q.edgeGroupCrossings,
    groupLabelX: q.groupLabelOverlaps,
    labelX: q.labelOverlaps,
    maxDeg: q.maxNodeDegree,
    aspect: q.aspectRatio.toFixed(2),
    ms: ms.toFixed(1),
    hard,
  };
}

async function main(): Promise<void> {
  const roots = parseRoots(process.argv.slice(2));
  const rows: Row[] = [];
  const placements: ElkNodePlacement[] = ['BRANDES_KOEPF', 'LINEAR_SEGMENTS', 'NETWORK_SIMPLEX'];
  const directions = ['right', 'down'] as const;

  for (const root of roots) {
    const project = loadProject(root);
    const theme = project.theme;
    const ids = listMapIds(project);
    for (const id of ids) {
      const loaded = loadMap(project, id);
      if (loaded.map.type !== 'graph') continue;
      const map = loaded.map;
      let sidecar = null;
      try {
        sidecar = readLayout(project, id);
      } catch {
        sidecar = null;
      }

      const legacyStart = performance.now();
      const legacy = layoutMap(map, theme, { sidecar });
      const legacyMs = performance.now() - legacyStart;
      const legacyRow = summarize(map, legacy, theme, root, 'legacy', 'legacy', legacyMs);
      legacyRow.map = id;
      rows.push(legacyRow);

      for (const engine of [
        { name: 'elk', flattenGroups: false },
        { name: 'elk-flat', flattenGroups: true },
      ]) {
        for (const nodePlacement of placements) {
          for (const direction of directions) {
            const variant = `${nodePlacement}/${direction}`;
            try {
              const start = performance.now();
              const layout = await layoutGraphElk(map, theme, { sidecar, nodePlacement, direction, flattenGroups: engine.flattenGroups });
              const ms = performance.now() - start;
              const row = summarize(map, layout, theme, root, engine.name, variant, ms);
              row.map = id;
              rows.push(row);
            } catch (error) {
              rows.push({
                root,
                map: id,
                engine: engine.name,
                variant: `${variant} ERROR: ${(error as Error).message}`,
              nodes: map.nodes.length,
              edges: map.edges.length,
              nodeX: -1,
              groupX: -1,
              containment: -1,
              edgeNodeX: -1,
              edgeX: -1,
              edgeGroupX: -1,
              groupLabelX: -1,
              labelX: -1,
              maxDeg: -1,
              aspect: '-',
              ms: '-',
              hard: -1,
            });
          }
        }
      }
    }
  }
  }

  const lines: string[] = [];
  lines.push('# Layout comparison: legacy vs ELK');
  lines.push('');
  lines.push('Generated by `node dist/compare-layouts.js --root . --root fixtures/ts-web`.');
  lines.push('Hard = nodeOverlaps + groupOverlaps + groupContainmentViolations + edgeNodeCrossings + labelOverlaps.');
  lines.push('');
  lines.push('| root | map | engine | variant | n | e | nodeX | groupX | contain | edgeNodeX | edgeX | edgeGroupX | groupLabelX | labelX | maxDeg | aspect | hard | ms |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const row of rows) {
    lines.push(
      `| ${path.basename(row.root)} | ${row.map} | ${row.engine} | ${row.variant} | ${row.nodes} | ${row.edges} | ${row.nodeX} | ${row.groupX} | ${row.containment} | ${row.edgeNodeX} | ${row.edgeX} | ${row.edgeGroupX} | ${row.groupLabelX} | ${row.labelX} | ${row.maxDeg} | ${row.aspect} | ${row.hard} | ${row.ms} |`,
    );
  }
  lines.push('');

  const maps = [...new Set(rows.map((row) => `${row.root}\u0000${row.map}`))];
  lines.push('## Per-map verdict');
  lines.push('');
  for (const key of maps) {
    const [root, map] = key.split('\u0000') as [string, string];
    const candidates = rows.filter((row) => row.root === root && row.map === map && row.engine.startsWith('elk') && row.hard >= 0);
    const legacy = rows.find((row) => row.root === root && row.map === map && row.engine === 'legacy');
    if (!candidates.length) {
      lines.push(`- **${map}**: no ELK result.`);
      continue;
    }
    const best = [...candidates].sort((a, b) => a.edgeX - b.edgeX || a.hard - b.hard || Number(a.ms) - Number(b.ms))[0]!;
    lines.push(
      `- **${map}** (${path.basename(root)}): best \`${best.engine}/${best.variant}\` edgeX=${best.edgeX} hard=${best.hard}, legacy edgeX=${legacy?.edgeX ?? '?'} hard=${legacy?.hard ?? '?'}.`,
    );
  }
  lines.push('');

  const out = path.join(process.cwd(), 'docs', 'layout-comparison.md');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');
  console.log(`Wrote ${out}`);
  console.log(`Rows: ${rows.length}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
