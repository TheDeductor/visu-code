import type { ProjectConfig } from '../core/types.js';
import { modeText } from './rules.js';

export function agentGuide(config: ProjectConfig, version = '0.1.0'): string {
  const limits = config.limits;
  const overview = limits.nodeCaps.overview;
  const feature = limits.nodeCaps.feature;
  const detail = limits.nodeCaps.detail;
  return `# VibeMap guide for coding agents

> Generated by VibeMap v${version}. Canonical instructions for this repository.
> Purpose: keep \`.vibemap/\` an accurate, small, visual description of this project so a human can understand it.
> Tracking mode: **${config.tracking.mode}**. Deepest map level to maintain: **${config.tracking.granularity}**.
> Offline, local-first. Never send project data to a network service.

## Golden rules

1. You describe **meaning**: what exists, how it connects, why. You never write coordinates, sizes, colours, fonts or layout. The tool owns those.
2. Every node of kind \`ui\`, \`page\`, \`component\`, \`api\`, \`service\`, \`module\`, \`function\`, \`file\`, \`database\`, \`queue\`, \`cache\`, \`storage\` or \`config\` needs \`refs\` pointing at real files (and a symbol when possible).
   - If you cannot point at code, it is probably not real. Do not add it.
   - Planned things: \`status: planned\` (no refs required).
   - Outside systems or people: kind \`external\` or \`actor\` (no refs required).
3. Do not invent technologies. If unsure whether Redis, Kafka, Stripe, etc. is used, search the code and config first.
4. Keep maps small: overview ≤ ${overview.soft} nodes (hard ${overview.hard}), feature ≤ ${feature.soft} (hard ${feature.hard}), detail ≤ ${detail.hard}. Labels ≤ ${limits.maxLabelChars} chars, descriptions ≤ ${limits.maxDescriptionChars} chars. Put long explanations in \`notes/\`.
5. Never edit \`.vibemap/layouts/\`, \`boards/\`, \`config.yaml\`, \`theme.yaml\`, \`locks.json\` or anything under \`.cache/\`.
6. Never change or delete a locked node. \`vibemap check\` and \`vibemap context\` list locks. Propose the change to the user instead.
7. IDs are stable kebab-case. Rename with the \`rename_node\` op, never by editing \`id\` fields.
8. \`evidence\`, coordinates, colours and sizes are computed by the tool. Writing them is an error (E013).
9. One map per feature or flow. The overview stays at ${overview.soft} nodes or fewer.

## Choose the right map type first

| You want to show | Use | Not |
|---|---|---|
| What the system is made of, at a glance | \`graph\`, level \`overview\`, ≤ ${overview.soft} nodes | everything in one map |
| One feature's components | \`graph\`, level \`feature\`, ≤ ${feature.soft} nodes | |
| A step-by-step flow over time (requests, an agent workflow, install steps) | \`sequence\` | a graph with groups |
| Database tables and relations | \`erd\` | a graph |
| Something none of the above can say | \`mermaid\` | |

If your description of the map contains "first… then… finally", it is a **sequence**.

## Size and density rules (hard)

- Overview ≤ ${overview.soft} nodes. Feature ≤ ${feature.soft}. Never more than ${limits.maxGroups} groups.
- Edges ≤ ${limits.warnEdgeRatio} × nodes warn, ${limits.maxEdgeRatio} × nodes error. If a node has more than ${limits.maxDegree} connections, it is a hub: put its targets in one group and draw ONE edge to the group, or split the map.
- Every edge must change the reader's understanding. Do not draw "obvious" edges (everything → logging, everything → config).
- Label at most ${Math.round(limits.maxLabelledEdgesRatio * 100)}% of edges. Labels ≤ ${limits.maxLabelChars} characters, verb phrases ("reads config", not "this reads the config file").
- Node labels ≤ ${limits.maxLabelChars} characters. Put detail in \`description\` (≤ ${limits.maxDescriptionChars} chars) or a note.

## Structure rules

- Left-to-right or top-to-bottom flow: sources/inputs first, outputs/stores last.
- Groups = real boundaries (process, layer, team). A node belongs to **one** group. Do not create a group for fewer than 2 nodes.
- Prefer layers: at most 3 to 4 stages in the main direction.
- Do not connect across more than 2 stages; add an intermediate node or drop the edge.
- Drill down, do not pile on: if a node deserves detail, give it a \`drill\` map.

## Process (always)

1. **Orient:** \`vibemap context --area <path-or-feature>\`, then decide the map type from the table above.
2. Write the smallest map that answers one question. Name the question in \`summary\`.
3. **Do the work** (write code).
4. **Update maps** with \`vibemap patch <map> --file ops.json\` (preferred) or edit the YAML directly for large changes.
5. **Verify:** \`vibemap check\`. Treat W120 to W127 as errors to fix, not noise. Do not declare done with errors.
6. \`vibemap inspect <map>\`: crossings should be ≤ 2 for overview, ≤ 4 for feature maps. If higher: remove edges, regroup, or split. Do not "fix" it by adding nodes.
7. **Record:** \`vibemap change add --title "…" --why "…" --maps <ids> --type feature\`.
8. For user-facing flows add a \`walkthrough\` and \`plain\` text on the key nodes.

## Things you must never do

- Never add nodes to make a diagram look complete.
- Never add an edge from every node to a shared utility.
- Never exceed limits and rely on the layout engine to cope.
- Never place or size anything. Never edit \`layouts/\`.

## Which map?

- \`00-overview\`: whole system, groups, major services, external systems, actors. Keep ≤ ${overview.soft} nodes.
- One map per feature or flow under \`maps/<feature>/\` (e.g. \`auth/login-flow\`).
- \`sequence\` maps for request flows; \`erd\` maps for data models.
- Create a map with \`vibemap map new <id> --type graph --title "…" --level feature\`.

## Map levels

- \`overview\`: components and external systems. No implementation details. ≤ ${overview.soft} nodes.
- \`feature\`: one flow, 3–${feature.soft} nodes, with refs and edges.
- \`detail\`: a tricky subsystem; still ≤ ${detail.hard} nodes. Link deeper maps with \`drill: <mapId>\`.

## Patch operations

\`\`\`json
{ "ops": [
  { "op": "add_node", "node": { "id": "session-store", "label": "Session store", "kind": "cache", "refs": [{ "path": "src/session.ts" }] } },
  { "op": "add_edge", "edge": { "from": "auth-api", "to": "session-store", "label": "save session", "kind": "writes" } },
  { "op": "update_node", "id": "auth-api", "set": { "description": "Checks credentials and creates a session." } },
  { "op": "rename_node", "id": "login-form", "to": "signin-form" },
  { "op": "remove_edge", "id": "auth-api>users-db:reads#0" },
  { "op": "set_meta", "set": { "summary": "…" } }
] }
\`\`\`

Other ops: \`remove_node\`, \`add_group\`, \`update_group\`, \`remove_group\`, \`update_edge\`, \`set_walkthrough\`, \`add_step\`, \`add_entity\`, \`add_field\`, \`add_relation\`, \`set_source\`.

Ops are atomic: all or nothing. They validate before writing and preserve YAML comments and key order. Use \`--dry-run\` to preview.

## Node kinds

\`ui\`, \`page\`, \`component\`, \`api\`, \`service\`, \`module\`, \`function\`, \`file\`, \`database\`, \`queue\`, \`cache\`, \`storage\`, \`external\`, \`actor\`, \`decision\`, \`process\`, \`config\`, \`note\`, \`custom\`.

## Edge kinds

\`calls\`, \`reads\`, \`writes\`, \`imports\`, \`data\`, \`event\`, \`depends\`, \`returns\`, \`flow\`, \`contains\`.

## Status values

\`planned\` (no refs needed, shown ghosted), \`built\` (refs required), \`deprecated\` (kept for history).

## Code refs

\`\`\`yaml
refs:
  - path: src/routes/auth.ts
    symbol: loginHandler   # optional, verified by the scanner
    lines: [12, 48]        # optional
\`\`\`

Paths are repo-relative, forward slashes. No absolute paths, no \`..\`.

## Common errors

- **E004** edge points at an unknown node — check spelling/case; use the exact id.
- **E007** ref path does not exist — file moved or typo; run \`vibemap scan\` and check \`git log --follow\`.
- **E008** symbol not found — the scanner did not find the symbol in that file; update the ref or the node.
- **E009** locked node modified — revert, or ask the user to unlock.
- **E015** above the absolute node cap — split the map.
- **E017** above the per-level node cap — split into a feature map and link with \`drill\`.
- **E018** edge/node ratio above ${limits.maxEdgeRatio} — remove edges or split the map.
- **W104** required refs missing — add refs or mark \`status: planned\`.
- **W120–W127** density warnings — treat them as errors and simplify the map.

Run \`vibemap schema --format md\` for the full file syntax.

## Mode-specific

${modeText(config.tracking.mode)}

Granularity: **${config.tracking.granularity}** — do not maintain maps deeper than this.

## Recording changes

\`\`\`bash
vibemap change add --title "Add email login" --why "Users need to sign in." --maps auth/login-flow,00-overview
\`\`\`

The delta is computed automatically. Never write \`delta\` or \`commit\` by hand.

## When you are stuck

Run \`vibemap doctor\`; run \`vibemap check --json\` for machine-readable errors; run \`vibemap context --area <path> --budget 800\` if context is large. Ask the user before modifying a lock.
`;
}
